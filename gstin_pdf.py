"""PDF report for a GSTIN check. Not an official GST certificate."""
from html import escape
from io import BytesIO

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle


def build_gstin_report(gstin: str, state: str, d: dict | None, validity: str,
                       disclaimer: str, generated_on: str) -> bytes:
    buf = BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4, leftMargin=18 * mm, rightMargin=18 * mm,
                            topMargin=16 * mm, bottomMargin=16 * mm,
                            title=f"GSTIN report {gstin}")
    ss = getSampleStyleSheet()
    small = ParagraphStyle("small", parent=ss["Normal"], fontSize=9, leading=12)

    story = [
        Paragraph("GSTIN verification report", ss["Title"]),
        Paragraph(f"Generated by GST TAXORA on {escape(generated_on)}. "
                  "This is not an official GST certificate.", small),
        Spacer(1, 8),
    ]
    rows = [
        ("GSTIN", gstin),
        ("State (from GSTIN)", state),
        ("Format and check character", validity),
    ]
    if d:
        rows += [
            ("Legal name", d["legal_name"]),
            ("Trade name", d["trade_name"] or "-"),
            ("Principal place of business", d["address"] or "-"),
            ("Registration date", d["reg_date"] or "-"),
            ("Business type", d["business_type"] or "-"),
            ("Taxpayer category", d["category"] or "-"),
            ("Registration status (as entered)", d["status"]),
            ("Details entered by", f"User, on {d['saved_on']}. Not verified by GST TAXORA."),
        ]
    else:
        rows.append(("Business details", "Not saved. Verify on the official GST portal."))

    table = Table(
        [[Paragraph(f"<b>{escape(k)}</b>", small), Paragraph(escape(str(v)), small)] for k, v in rows],
        colWidths=[60 * mm, 110 * mm],
    )
    table.setStyle(TableStyle([
        ("GRID", (0, 0), (-1, -1), 0.4, colors.grey),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("BACKGROUND", (0, 0), (0, -1), colors.HexColor("#F3F3F3")),
    ]))
    story += [table, Spacer(1, 12), Paragraph(escape(disclaimer), small)]
    doc.build(story)
    return buf.getvalue()
